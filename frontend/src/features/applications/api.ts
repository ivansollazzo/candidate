import type { ApplicationStatus } from "@/features/applications/status"
import type { Job } from "@/features/background_jobs/api"
import { json, request, type TaskStatus, uploadMany } from "@/shared/lib/http"
import type { SkillLevel } from "@/shared/lib/skills"

type JobSkill = { name: string; importance: "required" | "nice_to_have" | string }

export interface ApplicationSummary {
  id: number
  title: string | null
  company: string | null
  location: string | null
  work_mode: string | null
  salary: string | null
  salary_period: "annual" | "monthly" | "daily" | "hourly" | null
  salary_basis: "gross" | "net" | null
  status: ApplicationStatus
  applied_on: string | null
  created_at: string
  updated_at: string
}

export interface ApplicationListItem extends ApplicationSummary {
  /** Date of the latest agenda event, status changes excluded */
  last_event_on: string | null
  /** Score of the compatibility report, when one has been generated */
  match_score: number | null
  /** The report should be regenerated */
  report_stale: boolean
  /** Skills the report found missing from the profile, soft skills excluded */
  missing_skills: string[]
}

export interface ApplicationEvent {
  id: number
  application_id: number
  type: string
  occurred_on: string
  /** "HH:MM:SS" or null */
  starts_at: string | null
  /** "HH:MM:SS" or null; only with a start time */
  ends_at: string | null
  title: string
  details: string | null
  completed: boolean
  created_at: string
}

/** Event with its application's data, for the agenda and overview */
export interface AgendaEvent extends ApplicationEvent {
  application_title: string | null
  application_company: string | null
}

export type EventFields = Pick<ApplicationEvent, "application_id" | "type" | "occurred_on" | "starts_at" | "ends_at" | "title" | "details" | "completed">

export interface ReportSkill {
  skill: string
  importance: string
  kind: "technical" | "language" | "soft"
  status: "match" | "partial" | "missing"
  matched_with: string | null
  level: SkillLevel | null
  reason: string | null
  note: string | null
}

/** Compatibility report generated by the local model, or the error of a failed generation */
interface Report {
  score?: number
  skills?: ReportSkill[]
  summary?: string
  strengths?: string[]
  improvements?: { skill: string; suggestion: string }[]
  generated_at?: string
  error?: string
}

export interface Attachment {
  id: number
  filename: string
  content_type: string | null
  size: number
  created_at: string
}

export interface Application extends ApplicationSummary {
  contract_type: string | null
  seniority: string | null
  responsibilities: string[]
  requirements: string[]
  nice_to_have: string[]
  benefits: string[]
  skills: JobSkill[]
  languages: string[]
  education_required: string | null
  experience_years_min: number | null
  source_url: string | null
  contact_name: string | null
  contact_email: string | null
  notes: string | null
  has_description: boolean
  report: Report | null
  report_status: TaskStatus | null
  /** The skills changed after the report was generated */
  report_stale: boolean
  events: ApplicationEvent[]
  attachments: Attachment[]
}

export type ApplicationBulk =
  | { ids: number[]; action: "delete" }
  | { ids: number[]; action: "status"; status: ApplicationStatus }

/** Where to read the job posting: pasted text, link or file; none for the saved one */
export type JobSource = { text: string } | { url: string } | { file: File }

const sourceForm = (source?: JobSource, fields: Record<string, string> = {}): RequestInit => {
  const form = new FormData()
  for (const [key, value] of Object.entries({ ...source, ...fields })) form.append(key, value)
  return { method: "POST", body: form }
}

/** Editable application fields, plus the job posting text to store */
export type ApplicationChanges = Partial<Application> & { description?: string | null }

export const applicationsApi = {
  listApplications: () => request<ApplicationListItem[]>("/api/applications"),
  getApplication: (id: number) => request<Application>(`/api/applications/${id}`),
  createApplication: (fields: ApplicationChanges) => request<Application>("/api/applications", json("POST", fields)),
  updateApplication: (id: number, changes: ApplicationChanges) =>
    request<Application>(`/api/applications/${id}`, json("PATCH", changes)),
  deleteApplication: (id: number) => request<void>(`/api/applications/${id}`, { method: "DELETE" }),
  addAttachments: (id: number, files: File[]) =>
    request<Application>(`/api/applications/${id}/attachments`, uploadMany("POST", files)),
  deleteAttachment: (id: number, attachmentId: number) =>
    request<Application>(`/api/applications/${id}/attachments/${attachmentId}`, { method: "DELETE" }),
  /** Same action on several applications: all of them or none */
  bulkApplications: (bulk: ApplicationBulk) =>
    bulk.action === "delete"
      ? request<void>(`/api/applications?${bulk.ids.map((id) => `ids=${id}`).join("&")}`, { method: "DELETE" })
      : request<void>("/api/applications", json("PATCH", { ids: bulk.ids, status: bulk.status })),
  listEvents: () => request<AgendaEvent[]>("/api/events"),
  addEvent: (event: EventFields) => request<ApplicationEvent>("/api/events", json("POST", event)),
  updateEvent: (id: number, changes: Partial<EventFields>) => request<ApplicationEvent>(`/api/events/${id}`, json("PATCH", changes)),
  deleteEvent: (id: number) => request<void>(`/api/events/${id}`, { method: "DELETE" }),
  /** Saves the application with its posting right away; the AI fills it in the background */
  createApplicationWithAi: (source: JobSource, report: boolean) =>
    request<Application>("/api/applications/imports", sourceForm(source, { report: String(report) })),
  fillApplication: (id: number, source?: JobSource) => request<Job>(`/api/applications/${id}/fills`, sourceForm(source)),
}
