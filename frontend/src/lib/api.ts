const sourceForm = (source?: JobSource, fields: Record<string, string> = {}): RequestInit => {
  const form = new FormData()
  for (const [key, value] of Object.entries({ ...source, ...fields })) form.append(key, value)
  return { method: "POST", body: form }
}

